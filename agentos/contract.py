"""Контракт агента — один источник для всех способов его доставки.

Контракт уезжает к агенту двумя каналами: файлами-инструкциями (AGENTS.md и
его собратья) и полем instructions в рукопожатии MCP. Тексты у них разные —
в файле команды CLI, в MCP имена инструментов, — но правила обязаны быть
одни и те же.

Раньше они были написаны отдельно в install.py и mcp_server.py. Так они
неизбежно разъезжаются: правишь одно, забываешь другое, и агент через MCP
работает по одному контракту, а через файл — по другому. Поэтому здесь
лежат сами правила, а оба текста из них собираются.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Rule:
    """Одно правило контракта в двух формах доставки."""

    #: Когда это делать.
    when: str
    #: Команда CLI.
    cli: str
    #: Инструмент MCP.
    tool: str
    #: Что произойдёт, если проигнорировать.
    why: str


RULES: tuple[Rule, ...] = (
    Rule(
        when="Первое действие в каждой сессии",
        cli="agentctl resume --announce",
        tool="agentos_resume",
        why=(
            "Одна строка ответа скажет, есть ли незавершённая работа, чего она"
            " ждёт и когда продолжит. Если работа есть — продолжай её, не"
            " спрашивая человека «что дальше»."
        ),
    ),
    Rule(
        when="Новая задача от человека, сколь угодно абстрактная",
        cli='agentctl goal "…"',
        tool="agentos_goal",
        why=(
            "Система сама зафиксирует критерии приёмки, построит план задач и"
            " выдаст задания субагентам. Раскладывать задачу — твоя работа, не его."
        ),
    ),
    Rule(
        when="Задание выполнено",
        cli="agentctl task report <task_id> --json '{\"summary\":\"…\"}'",
        tool="agentos_task_report",
        why=(
            "Возвращай отчёт, а не транскрипт: на лимите из брифа держится вся"
            " экономия контекста. Результат, не отданный в AgentOS, теряется при"
            " обрыве сессии, как будто его не было."
        ),
    ),
    Rule(
        when="Упёрся в лимит токенов, доступ или необратимое действие",
        cli="agentctl task block <task_id> --reason quota|capability|approval",
        tool="agentos_task_block",
        why=(
            "Заблокированная задача не останавливает остальные ветки плана, а по"
            " квоте продолжится сама после сброса лимитов."
        ),
    ),
    Rule(
        when="Задачи кончились",
        cli="agentctl verify <mission_id>",
        tool="agentos_verify",
        why=(
            "Готово — это пройденная приёмка, а не отсутствие оставшейся работы."
            " Красный программный гейт отменяет любой вердикт, включая твой."
        ),
    ),
    Rule(
        when="Нужно что-то узнать о проекте",
        cli='agentctl memory search "…"',
        tool="agentos_memory_search",
        why=(
            "Память хранит факты этого проекта и общий опыт. Не спрашивай"
            " человека о том, что можешь узнать сам — из памяти, репозитория или"
            " запуска команды."
        ),
    ),
)

#: Что нельзя нарушать ни при каком способе доставки.
INVARIANTS: tuple[str, ...] = (
    "Красный программный гейт — это отказ. Тест не помечается skip, линтер не"
    " глушится, allowlist политики не расширяется ради «чтобы прошло».",
    "Не объявляй «готово» до приёмки: готово — когда подтверждены все критерии.",
    "Секреты не попадают в код, БД и логи. Нужен ключ — блокируй задачу с"
    " reason=capability и назови переменную окружения.",
)

HEADER = (
    "Этот воркспейс подключён к AgentOS — системе, которая держит состояние"
    " работы на диске и продолжает начатое сама: после обрыва сессии и после"
    " исчерпания лимитов токенов."
)

#: Как уживаются несколько мастер-агентов в одном проекте.
MULTI_AGENT_CLI = (
    "Мастер-агентов в проекте может быть несколько — по чату на задачу."
    " Назовись своим ID (`export AGENTOS_AGENT_ID=<имя>` или флаг `--agent"
    " <имя>` у любой команды), и ты будешь вести только свои миссии."
    " Без этого все чаты работают под общим агентом `default` и подхватывают"
    " работу друг друга. Чужие миссии видно через `agentctl status --all`."
)
MULTI_AGENT_MCP = (
    "Мастер-агентов в проекте может быть несколько — по чату на задачу."
    " Передавай своё имя в поле `agent` у `agentos_resume`, `agentos_goal` и"
    " `agentos_status`, и ты будешь вести только свои миссии. Без этого все"
    " чаты работают под общим агентом `default` и подхватывают работу друг друга."
)


def render_markdown() -> str:
    """Текст для файлов-инструкций: AGENTS.md, CLAUDE.md, GEMINI.md."""
    lines = ["## AgentOS", "", HEADER, ""]
    for rule in RULES:
        lines += [f"**{rule.when}:**", "", "```bash", rule.cli, "```", "", rule.why, ""]
    lines += ["**Несколько задач параллельно:**", "", MULTI_AGENT_CLI, ""]
    lines += ["**Чего нельзя делать:**", ""]
    lines += [f"- {item}" for item in INVARIANTS]
    lines += [
        "",
        "Полный контракт — [AGENTS.md](AGENTS.md). Если у тебя есть инструменты"
        " `agentos_*`, работай через них: это тот же контракт вызовами.",
    ]
    return "\n".join(lines)


def render_instructions() -> str:
    """Текст для рукопожатия MCP: то же самое, но через инструменты."""
    lines = [
        "AgentOS — система автономных агентов с состоянием на диске.",
        "",
        "Работай через её инструменты, а не в обход: результат, не отданный в"
        " AgentOS, теряется при обрыве сессии, как будто его не было.",
        "",
        "Порядок работы:",
        "",
    ]
    for index, rule in enumerate(RULES, start=1):
        lines.append(f"{index}. {rule.when} — `{rule.tool}`. {rule.why}")
    lines += ["", MULTI_AGENT_MCP, "", "Чего нельзя делать:", ""]
    lines += [f"- {item}" for item in INVARIANTS]
    return "\n".join(lines)


def operations() -> tuple[tuple[str, str], ...]:
    """Пары «команда CLI, инструмент MCP» — для проверки полноты обоих текстов."""
    return tuple((rule.cli, rule.tool) for rule in RULES)
