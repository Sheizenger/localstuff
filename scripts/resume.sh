#!/usr/bin/env bash
# Продолжить незавершённые прогоны. Вызывается SessionStart-хуком и вручную.
# --announce печатает ОДНУ строку статуса, чтобы не жечь контекст сессии.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"
cd "$ROOT"

# Хук не должен ронять сессию, если окружение ещё не собрано.
# Проверяется именно наличие AgentOS, а не каталога состояния: раньше здесь
# стоял путь var/, состояние переехало в .agentos/var, и хук молча выходил
# всегда — то есть подхват работы на старте сессии просто не срабатывал.
if ! agentos_available; then
  exit 0
fi

agentctl resume "$@" || true
